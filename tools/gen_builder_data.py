"""Generates src/builder_data.inc (template slot + per-mission story table) and the starter presets.

  python gen_builder_data.py FRESH.sav FRESH_SLOT BASELINE_DIR OUT_INC PRESET_ROOT
"""
import json
import os
import re
import struct
import sys

import dmc1_save as m
import dmc1_builder as b

S = m.SLOT_SIZE

ITEM_NAMES = {0x0A: "Vital Star", 0x0B: "Devil Star", 0x0C: "Untouchable", 0x0D: "Holy Water"}
MOVE_NAMES = m.MOVE_BITS
DIFF_NAMES = {2: "easy", 3: "normal", 5: "hard", 6: "dmd"}
ARM_NAMES = {(0, 0): "Alastor", (1, 0): "Ifrit", (4, 0): "Force Edge", (4, 1): "Sparda", (0, 2): "Yamato"}
GUN_NAMES = {1: "Handguns", 2: "Shotgun", 3: "Grenadegun", 4: "Nightmare-Beta"}


def c_bytes(data):
    return ",".join(f"0x{x:02X}" for x in data)


def main():
    fresh_path, fresh_slot, base_dir, out_inc, preset_root = sys.argv[1:6]
    fresh = b.slot_of(fresh_path, int(fresh_slot))
    table = b.make_table(fresh, base_dir)

    lines = ["// Generated by tools/gen_builder_data.py. Do not edit by hand.", ""]
    lines.append(f"static const unsigned char kTemplateSlot[{S}] = {{{c_bytes(fresh)}}};")
    lines.append("")
    entries = []
    for key in sorted(table, key=int):
        e = table[key]
        mis = int(key)
        story = sorted((int(o, 16), v) for o, v in e["story"].items())
        lines.append(f"static const StoryByte kStory{mis}[] = {{" +
                     ",".join(f"{{0x{o:03X},0x{v:02X}}}" for o, v in story) + "};")
        items = [(0, w, 1) for w in e["weapons"]] + [tuple(x) for x in e["key_items"]] + \
                [tuple(x) for x in e["other_items"]]
        lines.append(f"static const ItemEntry kItems{mis}[] = {{" +
                     ",".join(f"{{{c},{i},{n}}}" for c, i, n in items) + "};")
        arm, gun, model = e["equip"]
        entries.append(f"    {{{mis}, kStory{mis}, {len(story)}, kItems{mis}, {len(items)}, "
                       f"{arm}, {gun}, {model}, {e['dt_gauge']}}},")
    lines.append("")
    lines.append("static const MissionData kMissions[] = {")
    lines += entries
    lines.append("};")
    open(out_inc, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out_inc}: {len(table)} missions")

    # ---- Starter presets ----
    clean_dir = os.path.join(preset_root, "Clean")
    route_dir = os.path.join(preset_root, "Any% Normal (route)")
    os.makedirs(clean_dir, exist_ok=True)
    os.makedirs(route_dir, exist_ok=True)
    for key in sorted(table, key=int):
        mis = int(key)
        clean = {
            "name": f"Mission {mis}",
            "mission": mis,
            "difficulty": "normal",
            "costume": "dante",
            "orbs": 0,
            "dt_gauge": "full",
            "moves": [],
            "items": {},
        }
        json.dump(clean, open(os.path.join(clean_dir, f"M{mis:02}.json"), "w"), indent=2)

        base = open(os.path.join(base_dir, f"M{mis:02}.sav"), "rb").read()[0:S]
        items, _ = m.read_items(base)
        moves = struct.unpack_from("<H", base, m.OFF_MOVES)[0]
        e = table[key]
        route = {
            "name": f"Mission {mis} (route loadout)",
            "mission": mis,
            "difficulty": DIFF_NAMES[base[m.OFF_DIFFICULTY]],
            "costume": "dante",
            "orbs": struct.unpack_from("<I", base, m.OFF_ORBS)[0],
            "hp_bars": base[m.OFF_HP_BAR],
            "dt_bars": base[m.OFF_DT_BAR],
            "dt_gauge": "route",
            "moves": [MOVE_NAMES[bit] for bit in sorted(MOVE_NAMES) if moves >> bit & 1],
            "items": {ITEM_NAMES[i]: n for c, i, n in items if c == 2 and i in ITEM_NAMES},
            "equip": {
                "devil_arm": ARM_NAMES[(e["equip"][0], e["equip"][2])],
                "gun": GUN_NAMES[e["equip"][1]],
            },
        }
        json.dump(route, open(os.path.join(route_dir, f"M{mis:02}.json"), "w"), indent=2)
    print(f"wrote presets for {len(table)} missions into {clean_dir} and {route_dir}")


if __name__ == "__main__":
    main()
